import React, { useState } from 'react';
import { useApp } from '../context/AppContext';
import { Clock, CheckCircle2, Circle, ArrowRight, Zap, Sparkles, X } from 'lucide-react';

export default function DailyPlanModal({ onNavigate }) {
  const {
    showDailyPlanModal,
    setShowDailyPlanModal,
    dailyPlan,
    loadingDailyPlan,
    triggerCelebration,
    refreshDashboard
  } = useApp();

  const [completedSteps, setCompletedSteps] = useState({});

  if (!showDailyPlanModal) return null;

  const toggleStep = (step) => {
    setCompletedSteps(prev => {
      const next = { ...prev, [step]: !prev[step] };
      const allDone = dailyPlan?.activities?.every(act => next[act.step]);
      if (allDone) {
        triggerCelebration();
        refreshDashboard();
      }
      return next;
    });
  };

  const handleStartActivity = (route) => {
    setShowDailyPlanModal(false);
    if (onNavigate) {
      const cleanRoute = route.replace('/', '');
      onNavigate(cleanRoute);
    }
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-900/60 backdrop-blur-sm animate-fade-in">
      <div className="bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800 rounded-3xl p-6 sm:p-8 max-w-lg w-full shadow-2xl relative">
        <button
          onClick={() => setShowDailyPlanModal(false)}
          className="absolute top-5 right-5 p-2 rounded-xl text-slate-400 hover:text-slate-600 dark:hover:text-slate-200 hover:bg-slate-100 dark:hover:bg-slate-800"
        >
          <X className="w-5 h-5" />
        </button>

        <div className="flex items-center gap-3 mb-2">
          <div className="w-12 h-12 rounded-2xl bg-gradient-to-tr from-amber-500 to-orange-400 text-white flex items-center justify-center shadow-md">
            <Clock className="w-6 h-6" />
          </div>
          <div>
            <h3 className="text-lg font-bold text-slate-900 dark:text-white flex items-center gap-2">
              10-Minute Daily Plan
              <span className="text-[10px] uppercase font-extrabold px-2 py-0.5 rounded-full bg-amber-100 dark:bg-amber-950 text-amber-700 dark:text-amber-300">
                Personalized
              </span>
            </h3>
            <p className="text-xs text-slate-500 dark:text-slate-400">
              Generated by Orchestrator Agent to target your weakest skill areas.
            </p>
          </div>
        </div>

        {loadingDailyPlan ? (
          <div className="py-12 flex flex-col items-center justify-center text-center">
            <div className="w-10 h-10 border-3 border-amber-500 border-t-transparent rounded-full animate-spin mb-3" />
            <p className="text-xs text-slate-500 font-medium">Orchestrator Agent analyzing your mastery curve...</p>
          </div>
        ) : dailyPlan ? (
          <div className="my-5 space-y-3">
            <div className="flex items-center justify-between px-1 text-xs text-slate-500 dark:text-slate-400">
              <span className="font-semibold text-slate-700 dark:text-slate-300">Theme: {dailyPlan.theme}</span>
              <span className="flex items-center gap-1 font-bold text-amber-600 dark:text-amber-400">
                <Zap className="w-3.5 h-3.5 fill-amber-500" />
                +{dailyPlan.xp_reward || 60} XP
              </span>
            </div>

            <div className="space-y-2.5">
              {dailyPlan.activities?.map((act) => {
                const isCompleted = Boolean(completedSteps[act.step]);
                return (
                  <div
                    key={act.step}
                    className={`p-3.5 rounded-2xl border transition-all flex items-center justify-between gap-3 ${
                      isCompleted
                        ? 'bg-emerald-50/70 border-emerald-200 dark:bg-emerald-950/40 dark:border-emerald-800/60'
                        : 'bg-slate-50/80 border-slate-200/80 dark:bg-slate-800/40 dark:border-slate-800'
                    }`}
                  >
                    <button
                      onClick={() => toggleStep(act.step)}
                      className="shrink-0 text-slate-400 hover:text-emerald-500 transition-colors"
                      title={isCompleted ? "Mark incomplete" : "Mark completed"}
                    >
                      {isCompleted ? (
                        <CheckCircle2 className="w-5 h-5 text-emerald-500 fill-emerald-100 dark:fill-emerald-950" />
                      ) : (
                        <Circle className="w-5 h-5" />
                      )}
                    </button>

                    <div className="flex-1 min-w-0">
                      <div className="flex items-center gap-2 mb-0.5">
                        <span className="text-[10px] font-bold uppercase tracking-wider px-1.5 py-0.5 rounded bg-slate-200 dark:bg-slate-700 text-slate-700 dark:text-slate-300">
                          {act.duration_minutes}m • {act.skill}
                        </span>
                        <h4 className={`text-xs font-bold truncate ${isCompleted ? 'line-through text-slate-400 dark:text-slate-500' : 'text-slate-900 dark:text-white'}`}>
                          {act.title}
                        </h4>
                      </div>
                      <p className="text-[11px] text-slate-500 dark:text-slate-400 line-clamp-1">
                        {act.description}
                      </p>
                    </div>

                    <button
                      onClick={() => handleStartActivity(act.route)}
                      className="shrink-0 py-1.5 px-3 rounded-xl bg-slate-900 hover:bg-slate-800 dark:bg-white dark:hover:bg-slate-100 text-white dark:text-slate-900 text-xs font-bold flex items-center gap-1 shadow-xs hover:scale-102 transition-all"
                    >
                      <span>Go</span>
                      <ArrowRight className="w-3 h-3" />
                    </button>
                  </div>
                );
              })}
            </div>
          </div>
        ) : null}

        <div className="pt-2 flex justify-between items-center text-xs text-slate-400">
          <span>Complete all 3 tasks to keep your streak burning 🔥</span>
        </div>
      </div>
    </div>
  );
}
